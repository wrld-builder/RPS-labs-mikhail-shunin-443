"""
Алгоритм сортировки кучей (Heap Sort)

Heap Sort - это алгоритм сортировки, использующий структуру данных "куча" (heap).
Время работы: O(n log n) в любом случае
Пространственная сложность: O(1) (сортировка in-place)
"""


def heapify(arr, n, i):
    """
    Преобразует поддерево в максимальную кучу (max heap).
    
    Параметры:
    arr - массив для сортировки
    n - размер кучи (количество элементов)
    i - индекс корневого элемента поддерева
    
    Эта функция находит наибольший элемент среди:
    - корня (arr[i])
    - левого потомка (arr[2*i + 1])
    - правого потомка (arr[2*i + 2])
    Если наибольший элемент не является корнем, он меняется местами с корнем,
    и функция рекурсивно вызывается для поддерева.
    """
    largest = i  # Инициализируем наибольший элемент как корень
    left = 2 * i + 1  # Индекс левого потомка
    right = 2 * i + 2  # Индекс правого потомка

    # Проверяем, существует ли левый потомок и больше ли он корня
    if left < n and arr[left] > arr[largest]:
        largest = left

    # Проверяем, существует ли правый потомок и больше ли он корня
    if right < n and arr[right] > arr[largest]:
        largest = right

    # Если наибольший элемент не является корнем, меняем их местами
    if largest != i:
        arr[i], arr[largest] = arr[largest], arr[i]
        # Рекурсивно применяем heapify к поддереву
        heapify(arr, n, largest)


def heap_sort(arr):
    """
    Основная функция сортировки кучей.
    
    Алгоритм работает в два этапа:
    1. Построение максимальной кучи (max heap) из входного массива
    2. Извлечение элементов из кучи по одному и размещение их в отсортированном порядке
    
    Параметры:
    arr - массив для сортировки (будет изменен in-place)
    
    Возвращает:
    Отсортированный массив (или None, так как сортировка in-place)
    """
    n = len(arr)

    # Этап 1: Построение максимальной кучи
    # Начинаем с последнего родительского узла и двигаемся вверх
    # Родительский узел находится на позиции (n // 2 - 1)
    # Это гарантирует, что все поддеревья станут кучами
    for i in range(n // 2 - 1, -1, -1):
        heapify(arr, n, i)

    # Этап 2: Извлечение элементов из кучи по одному
    # На каждом шаге:
    # - Корень кучи (наибольший элемент) перемещается в конец массива
    # - Размер кучи уменьшается на 1
    # - Куча перестраивается для оставшихся элементов
    for i in range(n - 1, 0, -1):
        # Перемещаем текущий корень в конец
        # Это наибольший элемент из оставшихся
        arr[0], arr[i] = arr[i], arr[0]
        
        # Вызываем heapify для уменьшенной кучи
        # Теперь размер кучи равен i (последний элемент уже на своем месте)
        heapify(arr, i, 0)

    return arr


# Пример использования
